export function pickAvatarMessage(level: number, discomfort: number): string {
  const band = bandFromScore(discomfort);
  const pool = MESSAGES[level]?.[band] ?? MESSAGES[1].mid;
  return pool[Math.floor(Math.random() * pool.length)];
}
